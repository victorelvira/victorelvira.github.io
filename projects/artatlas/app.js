const deacc = s => (s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
function renderPainterList() {
  const q = deacc((document.getElementById("painters-search")?.value || "").trim());  // accent-insensitive
  const ul = document.getElementById("painters-list");
  let html = "";

  const museumRow = m =>
    `<li class="mrow" data-museum="${esc(m.key)}"><span class="micon">🏛</span><div>` +
    `<div class="mname">${esc(m.location)}</div>` +
    `<div class="msub">${esc([m.city, m.country].filter(Boolean).join(", "))} · ${m.count} works · ` +
    `${m.painters.size} painter${m.painters.size > 1 ? "s" : ""}</div></div></li>`;

  if (q) {   // when searching: matching museums first (there are hundreds otherwise)
    const mus = museumIndex.filter(m =>
      deacc(m.location).includes(q) || deacc(m.city).includes(q)).slice(0, 8);
    if (mus.length) html += `<li class="pop-h">Museums</li>` + mus.map(museumRow).join("");
  }

  const painterRow = p => {
    const on = state.painters[p.name] !== false;
    const yr = BORN[p.slug] ? ` <span class="pyr">b. ${BORN[p.slug]}</span>` : "";
    return `<li class="prow"><label><input type="checkbox" data-painter="${esc(p.name)}"${on ? " checked" : ""}>` +
      `<span class="sw" style="background:${on ? colorFor(p.name) : "#cfc7bd"}"></span>${esc(p.name)}${yr}</label>` +
      `<button type="button" class="only" data-only="${esc(p.name)}">only</button></li>`;
  };
  const pnt = PAINTERS.filter(p => deacc(p.name).includes(q) || deacc(nickOf(p)).includes(q));
  if (pnt.length) {
    if (q) {                                   // searching → flat list under one header (if mixed with museums)
      if (html) html += `<li class="pop-h">Painters</li>`;
      html += pnt.map(painterRow).join("");
    } else {                                   // idle → grouped by the active axis (period or school)
      const groups = painterGroupBy === "school" ? SCHOOLS : ERAS;
      const keysOf = painterGroupBy === "school" ? schoolsOf : erasOf;
      // ONLY throws everything else away, which is the right verb the first time and the wrong one
      // the second: once you have isolated the Baroque, the next thing you want is to *add* the
      // Renaissance, not to swap to it. So every group that is not already in shows ALSO beside it —
      // but only while something is left out, since with all 74 painters on there is nothing to add.
      const everythingOn = PAINTERS.every(p => state.painters[p.name] !== false);
      for (const g of groups) {
        const inGroup = pnt.filter(p => keysOf(p.slug).includes(g.key))
          .sort((a, z) => bornOf(a.slug) - bornOf(z.slug));   // chronological within the group
        if (!inGroup.length) continue;
        const allOn = inGroup.every(p => state.painters[p.name] !== false);
        html += `<li class="pop-h grp">` +
          `<label class="grp-tick" title="${esc(t("Tick/untick the whole group"))}">` +
          `<input type="checkbox" data-grp-tick="${esc(g.key)}"${allOn ? " checked" : ""}>` +
          `<span>${esc(t(g.label))}</span></label>` +
          (allOn || everythingOn ? "" :
            `<button type="button" class="grp-also" data-grp-also="${esc(g.key)}" ` +
            `title="${esc(t("Add these painters to the ones already shown"))}">${esc(t("also"))}</button>`) +
          `<button type="button" class="grp-only" data-grp-only="${esc(g.key)}" ` +
          `title="${esc(t("Show only these painters"))}">${esc(t("only"))}</button></li>` +
          inGroup.map(painterRow).join("");
      }
    }
  }

  if (!q && museumIndex.length) {   // idle state: surface the museum search
    html += `<li class="pop-h">Popular museums · type to search all ${museumIndex.length}</li>` +
      museumIndex.slice(0, 6).map(museumRow).join("");
  }
  ul.innerHTML = html || `<li class="pop-empty">no match</li>`;

  ul.querySelectorAll("input[data-painter]").forEach(cb => cb.addEventListener("change", () => {
    state.painters[cb.dataset.painter] = cb.checked;
    refresh(); updatePainterBtn(); renderPainterList();
  }));
  // "only" (Kayak-style): deselect everyone, keep just this painter
  ul.querySelectorAll("button[data-only]").forEach(b => b.addEventListener("click", e => {
    e.preventDefault(); e.stopPropagation();
    PAINTERS.forEach(p => { state.painters[p.name] = p.name === b.dataset.only; });
    refresh(); updatePainterBtn(); renderPainterList();
  }));
  // group "only": isolate a whole period/school (uses the active grouping axis)
  ul.querySelectorAll("button[data-grp-only]").forEach(b => b.addEventListener("click", e => {
    e.preventDefault(); e.stopPropagation();
    const gk = b.dataset.grpOnly;
    const keysOf = painterGroupBy === "school" ? schoolsOf : erasOf;
    PAINTERS.forEach(p => { state.painters[p.name] = keysOf(p.slug).includes(gk); });
    refresh(); updatePainterBtn(); renderPainterList();
  }));
  // group "also": add a whole period/school to what is already on screen
  ul.querySelectorAll("button[data-grp-also]").forEach(b => b.addEventListener("click", e => {
    e.preventDefault(); e.stopPropagation();
    const gk = b.dataset.grpAlso;
    const keysOf = painterGroupBy === "school" ? schoolsOf : erasOf;
    PAINTERS.forEach(p => { if (keysOf(p.slug).includes(gk)) state.painters[p.name] = true; });
    refresh(); updatePainterBtn(); renderPainterList();
  }));
  // group tick: add/remove a whole period/school without disturbing the others
  ul.querySelectorAll("input[data-grp-tick]").forEach(cb => cb.addEventListener("change", () => {
    const gk = cb.dataset.grpTick;
    const keysOf = painterGroupBy === "school" ? schoolsOf : erasOf;
    PAINTERS.forEach(p => { if (keysOf(p.slug).includes(gk)) state.painters[p.name] = cb.checked; });
    refresh(); updatePainterBtn(); renderPainterList();
  }));
  ul.querySelectorAll(".mrow").forEach(row => row.addEventListener("click", () => selectMuseum(row.dataset.museum)));
}

