function yearNum(p) {
  const m = (p.year || "").match(/1[2-9]\d{2}|20\d{2}/);   // 12xx+ (Giotto onward)
  return m ? +m[0] : null;
}
function inYear(p) {
  const y = yearNum(p);                       // unknown-date works stay visible
  return y == null || (y >= state.yearMin && y <= state.yearMax);
}
// a common free-text filter (title / painter / museum / city / country / year / medium),
// accent-insensitive, shared by every view via passesAll + tablePass
// A museum has one name here and another on its own door: we show "Museum of Fine Arts of Seville",
// Seville shows "Museo de Bellas Artes de Sevilla". Wikidata knows both (see i18n/), so the filter
// accepts either — you find a museum by typing it the way you know it, in any of our languages.
// Loaded once, lazily: it is only needed the first time somebody types.
let musI18n = null, musI18nSearch = new Map();
function loadMuseumNames() {
  if (musI18n) return;
  musI18n = {};                                   // set immediately so we only ever fetch once
  fetch("artatlas/data/museum_i18n.json?v=" + DATA_V)
    .then(r => r.ok ? r.json() : null)
    .then(d => {
      if (!d) return;
      musI18n = d.m || {};
      for (const [mid, names] of Object.entries(musI18n))
        musI18nSearch.set(mid, deacc(Object.values(names).join(" ")));
      if (state.q) refresh();                     // the answer arrived after they typed: redo it
    })
    .catch(() => {});
}
function matchesQ(p) {
  if (!state.q) return true;
  if ([p.painter, p.title, p.location, p.city, p.country, p.year, p.medium]
      .some(v => deacc(v).includes(state.q))) return true;
  const other = p.museum_id && musI18nSearch.get(p.museum_id);   // the museum in another language
  return !!other && other.includes(state.q);
}
function passesAll(p) {
  const kindOk = state.mode === "painted" ? true : state[p.kind || "museum"] !== false;   // no venue type on map 2
  const formOk = state[p.form || "painting"] !== false;
  const painterOk = state.painters[p.painter] !== false;
  const attrOk = !state.acceptedOnly || ATTR_ACCEPTED.has(p.attribution);
  const museumOk = !state.museumFilter || museumKey(p) === state.museumFilter;
  return painterOk && kindOk && formOk && attrOk && museumOk && inYear(p) && matchesQ(p);
}
// active coordinate per map: current location, or where it was painted (map 2)
function activeCoord(f) {
  if (state.mode === "painted") {
    const p = f.properties;
    return (p.creation_lat != null && p.creation_lon != null) ? [p.creation_lon, p.creation_lat] : null;
  }
  // "Private collection", "Stolen from …": we know the work exists, not where it is. It stays in the
  // table, in its painter's set and in the galaxy, but it gets no pin — the coordinate in the file is
  // a city centroid the geocoder invented. Map 2 still shows it, because where it was PAINTED is known.
  return f.properties.placeless ? null : f.geometry.coordinates;
}

function esc(s) {
  return String(s).replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
}

// subtle "?" for a disputed attribution (a scholarly nuance, not an error → not a warning ⚠)
function disputedMark(p) {
  if (!p.attribution || ATTR_ACCEPTED.has(p.attribution)) return "";
  // show WHY when we have a recorded reason, else the generic label
  const why = p.attribution_note || `${p.attribution} attribution`;
  return ` <span class="qm" title="${esc(why)}">?</span>`;
}

