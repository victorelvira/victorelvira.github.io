// clustering: overlapping venues (e.g. all of Rome) merge at low zoom into one badge
// showing the TOTAL number of works, and split apart as you zoom in.
const cluster = L.markerClusterGroup({
  maxClusterRadius: 44,
  showCoverageOnHover: false,
  spiderfyOnMaxZoom: true,
  iconCreateFunction(c) {
    // aggregate the painter-colour breakdown across all works in the cluster
    const agg = {};
    let works = 0;
    for (const m of c.getAllChildMarkers()) {
      const cc = m.options.colorCounts;
      if (cc) for (const [col, n] of Object.entries(cc)) { agg[col] = (agg[col] || 0) + n; works += n; }
      else works += (m.options.works || 1);
    }
    const size = works >= 25 ? 48 : works >= 10 ? 40 : 32;
    const { style, pie } = pieStyle(agg);
    return L.divIcon({
      html: `<div class="cl${pie ? " pie" : ""}" style="width:${size}px;height:${size}px;${style}"><span class="cl-n">${works}</span></div>`,
      className: "", iconSize: [size, size],
    });
  },
}).addTo(map);

