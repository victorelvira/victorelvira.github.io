// ── time slider: filter the map + panel by year of creation (dual-handle range) ──
function buildTimeline(min, max) {
  const lo = document.getElementById("tl-min");
  const hi = document.getElementById("tl-max");
  const label = document.getElementById("tl-label");
  const fill = document.getElementById("tl-fill");
  lo.min = hi.min = min; lo.max = hi.max = max;
  lo.value = min; hi.value = max;
  state.yearMin = min; state.yearMax = max;

  const paint = () => {
    const span = max - min || 1;
    const a = (state.yearMin - min) / span * 100;
    const b = (state.yearMax - min) / span * 100;
    fill.style.left = a + "%"; fill.style.right = (100 - b) + "%";
    label.textContent = state.yearMin === state.yearMax ? `${state.yearMin}` : `${state.yearMin}–${state.yearMax}`;
  };
  const update = () => {
    let a = +lo.value, b = +hi.value;
    if (a > b) { if (document.activeElement === lo) { b = a; hi.value = b; } else { a = b; lo.value = a; } }
    state.yearMin = a; state.yearMax = b;
    paint(); refresh();
  };
  lo.addEventListener("input", update);
  hi.addEventListener("input", update);
  paint();
}

// ── side panel: the works currently within the map viewport, grouped by venue ──
// Infinite scroll: render the list in chunks and append more as the user nears the bottom.
// Only a few thumbnails are ever near the viewport, so this stays smooth on mobile while
// still reaching every work — nothing is dropped. Lazy <img> means only visible thumbs fetch.
const PANEL_CHUNK = 80;
let panelQueue = [];    // flat render plan: {grp} headers and {w} work rows, in display order
let panelCursor = 0;
let panelIO = null;
let panelMode = "list";   // "list" | "gallery" (thumbnail grid)

// gallery tile — lazy thumbnail (click → lightbox) + caption (click → the work "ficha").
// `vis` is the index array the caption click resolves against (panelVis or the table's own).
function tileHTML(w, vis) {
  const i = vis.length; vis.push(w);
  const p = w.p;
  const cap = `${p.title || ""}${p.year ? ` (${p.year})` : ""} — ${p.location || ""}`;
  const img = p.image
    ? `<img class="th" src="${esc(p.image)}" data-full="${esc(fullImage(p.image))}" data-cap="${esc(cap)}" alt="" loading="lazy">`
    : `<span class="th ph"></span>`;
  const share = p.qid ? `<button class="gshare" data-i="${i}" title="Share this painting" aria-label="Share">🔗</button>` : "";
  return `<li class="gcell" data-i="${i}" title="${esc(cap)}">${img}${share}<div class="gmeta">` +
    `<div class="gm1">${esc(p.painter)}${p.year ? ` <span class="gy">· ${esc(p.year)}</span>` : ""}</div>` +
    (p.location ? `<div class="gm2">${esc(p.location)}${p.city ? `, ${esc(p.city)}` : ""}</div>` : "") +
    `</div></li>`;
}
function panelCellHTML(w) { return tileHTML(w, panelVis); }

function panelRowHTML(w) {
  const i = panelVis.length; panelVis.push(w);
  const p = w.p;
  const cap = `${p.title || ""}${p.year ? ` (${p.year})` : ""} — ${p.location || ""}`;
  const thumb = p.image
    ? `<img class="th" src="${esc(p.image)}" data-full="${esc(fullImage(p.image))}" data-cap="${esc(cap)}" alt="" loading="lazy">`
    : `<span class="th"></span>`;
  return `<li data-i="${i}">${thumb}<div>` +
    `<div class="wt">${esc(p.title || "Untitled")}${p.year ? ` <span class="sub">${esc(p.year)}</span>` : ""}${disputedMark(p)}</div>` +
    `<div class="sub">${painterTag(p)}${p.medium ? " · " + esc(p.medium) : ""}</div></div></li>`;
}

function appendPanelChunk() {
  const ul = document.getElementById("worklist");
  const oldSentinel = ul.querySelector(".sentinel");
  if (oldSentinel) oldSentinel.remove();
  const end = Math.min(panelCursor + PANEL_CHUNK, panelQueue.length);
  let html = "";
  for (; panelCursor < end; panelCursor++) {
    const e = panelQueue[panelCursor];
    if (e.grp) {
      if (panelMode === "gallery") continue;   // gallery is a flat grid — museum is on each tile
      html += `<li class="grp"><span>${esc(e.grp.location)}${e.grp.city ? ` · ${esc(e.grp.city)}` : ""}</span>` +
        `<span class="n">${e.grp.count}</span></li>`;
    } else {
      html += panelMode === "gallery" ? panelCellHTML(e.w) : panelRowHTML(e.w);
    }
  }
  ul.insertAdjacentHTML("beforeend", html);
  if (panelCursor < panelQueue.length) {           // more to come → sentinel + observe
    ul.insertAdjacentHTML("beforeend", `<li class="sentinel" aria-hidden="true"></li>`);
    const s = ul.querySelector(".sentinel");
    if (!panelIO) panelIO = new IntersectionObserver(
      es => { if (es.some(x => x.isIntersecting)) appendPanelChunk(); }, { rootMargin: "400px" });
    else panelIO.disconnect();
    panelIO.observe(s);
  } else if (panelIO) { panelIO.disconnect(); }
}

function renderPanel() {
  if (state.near) return;                       // near-me mode owns the side panel (renderNearMe)
  if (panelIO) panelIO.disconnect();
  const bounded = view.map;                    // when the map is hidden, list ALL works (no bounds)
  const b = bounded ? map.getBounds() : null;
  const vis = works.filter(w => passesAll(w.p) && (!bounded || b.contains([w.lat, w.lon])));

  // group by the active place (venue on map 1, creation city on map 2)
  const painted = state.mode === "painted";
  const groups = new Map();
  for (const w of vis) {
    const k = `${w.lat.toFixed(5)},${w.lon.toFixed(5)}`;
    if (!groups.has(k)) groups.set(k, {
      location: painted ? (w.p.creation_place || "Unknown") : (w.p.location || "Location"),
      city: painted ? "" : (w.p.city || ""), items: [],
    });
    groups.get(k).items.push(w);
  }
  const ordered = [...groups.values()].sort((a, z) =>
    (a.city || "zzz").localeCompare(z.city || "zzz") || a.location.localeCompare(z.location));

  document.getElementById("panel-head").textContent =
    `${vis.length} work${vis.length === 1 ? "" : "s"}${bounded ? " in view" : ""}`;

  const ul = document.getElementById("worklist");
  panelVis = [];
  if (!vis.length) {
    ul.innerHTML = `<li class="empty">Pan or zoom the map — the works in view are listed here.</li>`;
    return;
  }
  // flatten to a render plan, then stream it in chunks
  panelQueue = [];
  for (const g of ordered) {
    g.items.sort((a, z) => (yearNum(a.p) || 9999) - (yearNum(z.p) || 9999));
    panelQueue.push({ grp: { location: g.location, city: g.city, count: g.items.length } });
    for (const w of g.items) panelQueue.push({ w });
  }
  panelCursor = 0;
  ul.innerHTML = "";
  appendPanelChunk();
}

