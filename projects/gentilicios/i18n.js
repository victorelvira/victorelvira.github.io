const LANGS = ["es", "fr", "en"];
let LANG = (() => {
  // the hash is "#<id>" or "#<id>&l=fr" or just "#l=fr": the id lands in a parameter of its own and is ignored here
  const p = new URLSearchParams(location.hash.slice(1)).get("l");
  if (LANGS.includes(p)) return p;
  try { const s = localStorage.getItem("gentilicios.lang"); if (LANGS.includes(s)) return s; } catch (e) {}
  const nav = (navigator.languages || [navigator.language || "es"]).map(x => x.slice(0, 2));
  return nav.find(x => LANGS.includes(x)) || "es";
})();
function T(key, vars) {
  let s = I18N[LANG][key] ?? I18N.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(v == null ? "" : String(v));
  return s;
}
// like T, but null when the key does not exist: for labels that fall back to the raw data value
function TX(key, vars) {
  return (I18N[LANG][key] ?? I18N.es[key]) == null ? null : T(key, vars);
}
function setLang(l) {
  if (!LANGS.includes(l)) return;
  LANG = l;
  try { localStorage.setItem("gentilicios.lang", l); } catch (e) {}
}
// static texts in the HTML: <x data-t="key"> for the content, data-t-ph / data-t-title / data-t-aria for attributes
function applyStatic() {
  document.documentElement.lang = T("html.lang");
  document.title = T("doc.title");
  document.querySelectorAll("[data-t]").forEach(el => { el.innerHTML = T(el.dataset.t); });
  document.querySelectorAll("[data-t-ph]").forEach(el => { el.placeholder = T(el.dataset.tPh); });
  document.querySelectorAll("[data-t-title]").forEach(el => { el.title = T(el.dataset.tTitle); });
  document.querySelectorAll("[data-t-aria]").forEach(el => { el.setAttribute("aria-label", T(el.dataset.tAria)); });
  document.querySelectorAll("#lang-pick button").forEach(b => b.classList.toggle("on", b.dataset.lang === LANG));
}
