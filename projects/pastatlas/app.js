/* ================= PANEL WIDTH: the reader can drag its edge, and it is remembered ================= */
function initGrip(){
  const grip=$("grip"), panel=$("panel");
  const set=w=>{ w=Math.max(300,Math.min(720,w)); panel.style.flexBasis=w+"px"; return w; };
  const saved=store.get("pasta-panelw",null); if(saved) set(saved);
  grip.addEventListener("pointerdown",e=>{
    e.preventDefault(); grip.setPointerCapture(e.pointerId);
    const x0=e.clientX, w0=panel.getBoundingClientRect().width;
    const move=ev=>set(w0-(ev.clientX-x0));
    const up=()=>{ grip.removeEventListener("pointermove",move); grip.removeEventListener("pointerup",up); store.set("pasta-panelw",panel.getBoundingClientRect().width); };
    grip.addEventListener("pointermove",move); grip.addEventListener("pointerup",up);
  });
}

