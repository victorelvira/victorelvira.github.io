/* opts: p/s/d = region lists to tint; cls = extra classes per region; pins = [{city,kind,label,count,data}] */
function mapSVG({p=[],s=[],d=[],cls={},pins=[]}={}){
  const pid="hatch"+(++patN);
  let h=`<svg viewBox="0 0 351 460" role="img" aria-label="Italia"><defs><pattern id="${pid}" width="7" height="7" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="7" height="7" fill="var(--pasta)"/><rect width="3.5" height="7" fill="var(--sauce)"/></pattern></defs>`;
  for(const code of REG_ORDER){
    const inP=p.includes(code), inS=s.includes(code), inD=d.includes(code);
    let c = inP&&inS?"":inP?"p":inS?"s":inD?"d":"";
    if(cls[code]) c+=" "+cls[code];
    h+=`<path class="reg ${c}" data-reg="${code}" d="${PATHS[code]}"${inP&&inS?` style="fill:url(#${pid})"`:""}><title>${esc(regName(code))}</title></path>`;
  }
  // pins, with simple label collision avoidance (biggest first)
  const placed=[]; const seen=new Map();
  pins.forEach(pn=>{ if(!CITY[pn.city]) return; const key=pn.city+"|"+pn.kind; if(!seen.has(key)) seen.set(key,{...pn}); });
  const list=[...seen.values()].sort((a,b)=>(b.count||1)-(a.count||1));
  let out="";
  for(const pn of list){
    const [x,y]=proj(CITY[pn.city]); const right=x<240;
    const r = pn.kind==="dishfill" ? 5+2.2*Math.sqrt(pn.count||1)*1.6 : pn.kind==="dish" ? 7 : 3.6;
    const label = pn.label ?? pn.city;
    const w=label.length*6.2, lx=right?x+r+4:x-r-4-w, box=[lx,y-8,lx+w,y+5];
    const free=!placed.some(b=>!(box[2]<b[0]||box[0]>b[2]||box[3]<b[1]||box[1]>b[3]));
    out+=`<g class="pin ${pn.kind}"${pn.data?` data-city="${esc(pn.city)}"`:""}><circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"><title>${esc(label)}</title></circle>`;
    if(pn.kind==="dishfill" && pn.count>1) out+=`<text x="${x.toFixed(1)}" y="${(y+3.5).toFixed(1)}" text-anchor="middle">${pn.count}</text>`;
    if(free){ placed.push(box); out+=`<text class="lbl" x="${(right?lx:lx+w).toFixed(1)}" y="${(y+4).toFixed(1)}" text-anchor="${right?"start":"end"}">${esc(label)}</text>`; }
    out+="</g>";
  }
  return h+out+"</svg>";
}

