/* ================= FILTERING ================= */
function pastaOK(p, ignore){
  if(ignore!=="dough" && F.dough.size && !F.dough.has(p.dough)) return false;
  if(F.fresh!=="all" && p.fresh!==(F.fresh==="fresh")) return false;
  if(ignore!=="scope" && scope==="core" && !p.core) return false;
  if(ignore!=="scope" && scope==="pop" && !POP_SET.ps.has(p.id)) return false;
  if(F.area.size && !p.reg.some(r=>F.area.has(AREA_OF(r)))) return false;
  const ff=famsOfIngs(p.fill||[]);
  for(const d of F.diet){ if(DIET[d].p && !DIET[d].p(p)) return false; if(!DIET[d].s(ff)) return false; }
  return true;
}
function sauceOK(s, ignore){
  if(ignore!=="scope" && scope==="core" && !s.core) return false;
  if(ignore!=="scope" && scope==="pop" && !POP_SET.ss.has(s.id)) return false;
  if(F.area.size && !s.reg.some(r=>F.area.has(AREA_OF(r)))) return false;
  const f=famsOf(s);
  if(ignore!=="fam") for(const x of F.fam) if(!f.has(x)) return false;
  return sauceDietOK(s);
}
