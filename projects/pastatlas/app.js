/* ---- floating column header ---- */
let headIO=null, pageScrolls=false;
function setHeadOffset(px){
  const mx=$("mx"), head=mx.tHead; if(!head) return;
  const max=Math.max(0, mx.offsetHeight - head.offsetHeight - 40);
  const y=Math.round(Math.max(0,Math.min(px,max)));
  head.querySelectorAll("th").forEach(th=>th.style.transform=y?`translateY(${y}px)`:"");
  head.classList.toggle("floating",y>0);
}
function headFromScroll(){ pageScrolls=true; if(view==="matrix") setHeadOffset(-$("mx").getBoundingClientRect().top); }
function watchHead(){
  // IntersectionObserver sees the real visible area even when the page is framed at full height
  headIO?.disconnect();
  const mx=$("mx"); if(!mx.tHead) return;
  headIO=new IntersectionObserver(es=>{ if(pageScrolls) return; es.forEach(en=>setHeadOffset(en.intersectionRect.top-en.boundingClientRect.top)); },
    {threshold:Array.from({length:401},(_,i)=>i/400)});
  headIO.observe(mx);
}
window.addEventListener("scroll",headFromScroll,{passive:true});

